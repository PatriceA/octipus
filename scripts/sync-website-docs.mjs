#!/usr/bin/env node
// Publish shared reference docs without maintaining a second editable copy.
import { readFile, writeFile, mkdir, rm, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const targetArg = args.find((arg) => !arg.startsWith('--'));
if (!targetArg || args.some((arg) => arg.startsWith('--') && arg !== '--check')) {
  throw new Error('Usage: node scripts/sync-website-docs.mjs <website-directory> [--check]');
}
const target = path.resolve(targetArg);
await access(path.join(target, 'astro.config.mjs'));
const mapping = JSON.parse(await readFile(path.join(root, 'scripts/website-docs-map.json'), 'utf8'));
const remote = 'https://github.com/PatriceA/octipus/blob/main/';
const raw = 'https://raw.githubusercontent.com/PatriceA/octipus/main/';

function link(source, href, isImage = false) {
  if (/^(?:[a-z][a-z\d+.-]*:|\/|#)/i.test(href)) return href;
  const [, filename, suffix = ''] = href.match(/^([^?#]*)(.*)$/);
  const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(source), filename));
  if (mapping[resolved] && !isImage) return `/${mapping[resolved]}/${suffix}`;
  return `${isImage ? raw : remote}${resolved}${suffix}`;
}

function render(source, content) {
  const heading = content.match(/^# (.+)$/m);
  if (!heading) throw new Error(`Missing title in ${source}`);
  const title = heading[1].replace(/`/g, '');
  // Ordinary Markdown avoids interpreting TypeScript examples or braces as MDX.
  let body = content.replace(/^# .+\r?\n/, '');
  let fence;
  body = body.split('\n').map((line) => {
    const marker = line.match(/^\s*(`{3,}|~{3,})/);
    if (marker) {
      if (!fence) fence = marker[1];
      else if (marker[1][0] === fence[0] && marker[1].length >= fence.length) fence = undefined;
      return line;
    }
    if (fence) return line;
    return line.replace(/(!?\[[^\]]*\])\(([^\s)]+)(\s+"[^"]*")?\)/g,
      (_, label, href, tooltip = '') => `${label}(${link(source, href, label.startsWith('!'))}${tooltip})`)
      .replace(/^(\s*\[[^\]]+\]:\s*)(\S+)/, (_, label, href) => `${label}${link(source, href)}`);
  }).join('\n');
  return `---\ntitle: ${JSON.stringify(title)}\n---\n\n<!-- Generated by scripts/sync-website-docs.mjs. Edit ${source} in the Octipus repository. -->\n\n${body.trim()}\n\n---\n\n[Edit this page in the repository](${remote}${source}).\n`;
}

let drift = 0;
for (const [source, slug] of Object.entries(mapping)) {
  const output = path.join(target, 'src/content/docs', `${slug}.md`);
  const oldMdx = output.replace(/\.md$/, '.mdx');
  const expected = render(source, await readFile(path.join(root, source), 'utf8'));
  let actual;
  try { actual = await readFile(output, 'utf8'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  let duplicate = false;
  try { await access(oldMdx); duplicate = true; }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (actual === expected && !duplicate) continue;
  drift++;
  if (check) console.error(`Out of sync: ${source} -> ${slug}`);
  else {
    await mkdir(path.dirname(output), { recursive: true });
    await writeFile(output, expected);
    await rm(oldMdx, { force: true });
  }
}
console.log(`${Object.keys(mapping).length} shared pages; ${drift} ${check ? 'out of sync' : 'updated'}.`);
if (check && drift) process.exitCode = 1;
